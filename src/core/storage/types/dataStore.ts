/**
 * The persistent data port: projects, conversation history and non-secret
 * state, with no host in sight.
 *
 * What belongs here is everything Seshyina must remember between runs that is
 * *not* a credential. What must never come here is a secret value: an
 * implementation stores `apiKeyRef`-style pointers, and the value behind a
 * pointer stays in the `SecretStore`. `assertNoSecretFields` is the runtime
 * guard for that rule, and `normalizeProject` drops any field the port does not
 * declare, so a caller that hands over an extra property cannot leak it to disk.
 *
 * Design note — filesystem/JSON rather than SQLite: this data is small, is read
 * and written by a single local process, and has to be inspectable by hand when
 * something goes wrong. A native SQLite binding would add a build-time
 * dependency to buy queries nobody runs yet. If the transcript outgrows a single
 * JSON file, swapping the implementation behind this port is the only change
 * required; nothing above it names a file.
 */
import { ValidationError } from '../../errors';
import type { ChatMessage, ToolCallRequest } from '../../providers/chat/types';

/** A project the user works in. `rootPath` is what a `Workspace` is built from. */
export interface ProjectRecord {
	readonly id: string;
	readonly name: string;
	/** Absolute path to the project directory. Never used to open a connection. */
	readonly rootPath: string;
	/** ISO-8601 timestamp. */
	readonly createdAt: string;
	/** ISO-8601 timestamp, bumped by every write to the record. */
	readonly updatedAt: string;
}

/**
 * Roles persisted in a transcript.
 *
 * `system` is included from the start of a conversation rather than being
 * injected at request time: the transcript *is* the request, so storing the
 * prompt with the rest means there is exactly one source of truth about what
 * the model was told, and what the user can edit is what the next turn sends.
 */
export type ConversationRole = 'system' | 'user' | 'assistant' | 'tool';

/**
 * One stored message.
 *
 * `seq` is the position the message occupies in the conversation, assigned at
 * append time under the store's write lock. It exists so the order is a fact on
 * disk and not only an accident of array ordering — a transcript that was
 * edited by hand, or written by an older version, is still readable.
 */
export interface ConversationMessage {
	readonly id: string;
	readonly seq: number;
	readonly role: ConversationRole;
	readonly content: string;
	readonly createdAt: string;
	/** Set on `tool` messages, matching the runtime's `ChatMessage`. */
	readonly toolCallId?: string;
	/**
	 * Set on the `assistant` message that asked for the calls its following
	 * `tool` messages answer.
	 *
	 * Persisted rather than reconstructed from the `[tool calls: …]` summary,
	 * because the summary carries no ids — and the next turn needs them, or the
	 * transcript it reloads asks a strict server to pair `role:"tool"` messages
	 * with calls that were never announced.
	 */
	readonly toolCalls?: readonly ToolCallRequest[];
}

export interface ConversationRecord {
	readonly id: string;
	/**
	 * The provider this conversation talks to.
	 *
	 * Separate from `projectId` on purpose: a conversation is bound to exactly
	 * one provider, but a project is optional. They used to be the same field,
	 * which made a conversation's workspace unknowable the moment a real project
	 * existed.
	 */
	readonly providerId?: string;
	/** The project this conversation works in, when it is bound to one. */
	readonly projectId?: string;
	readonly title: string;
	readonly createdAt: string;
	readonly updatedAt: string;
	/** Full transcript, ordered by `seq` ascending. */
	readonly messages: readonly ConversationMessage[];
}

/** A conversation without its transcript, for list views. */
export type ConversationSummary = Omit<ConversationRecord, 'messages'> & {
	readonly messageCount: number;
};

export interface CreateProjectInput {
	/** Generated by the implementation when omitted. */
	readonly id?: string;
	readonly name: string;
	readonly rootPath: string;
	readonly createdAt?: string;
}

export interface UpdateProjectInput {
	readonly name?: string;
	readonly rootPath?: string;
}

export interface CreateConversationInput {
	readonly id?: string;
	/** The provider this conversation talks to. */
	readonly providerId?: string;
	/** The project this conversation works in, when it is bound to one. */
	readonly projectId?: string;
	readonly title?: string;
	readonly createdAt?: string;
}

export interface AppendMessageInput {
	readonly role: ConversationRole;
	readonly content: string;
	readonly toolCallId?: string;
	/** Set on the `assistant` message that announced these calls. */
	readonly toolCalls?: readonly ToolCallRequest[];
	/** Generated by the implementation when omitted. */
	readonly id?: string;
	readonly createdAt?: string;
}

/**
 * Everything Seshyina persists locally.
 *
 * Reads are total: a missing record is `undefined`/`[]`, never an exception, so
 * a first run and a cleared directory behave identically. Writes reject
 * malformed input with `ValidationError`, because silently dropping a project
 * the user just created is worse than an error they can see.
 */
export interface DataStore {
	// Projects.
	listProjects(): Promise<readonly ProjectRecord[]>;
	getProject(projectId: string): Promise<ProjectRecord | undefined>;
	createProject(input: CreateProjectInput): Promise<ProjectRecord>;
	updateProject(projectId: string, input: UpdateProjectInput): Promise<ProjectRecord>;
	/** Returns false when the id was already absent. Cascades to conversations. */
	deleteProject(projectId: string): Promise<boolean>;

	// Conversations.
	/**
	 * Conversations, optionally filtered.
	 *
	 * `providerId` is the filter the chat uses; `projectId` is kept because the
	 * cascade on `deleteProject` needs it. Passing neither returns everything.
	 */
	listConversations(filter?: {
		readonly providerId?: string;
		readonly projectId?: string;
	}): Promise<readonly ConversationSummary[]>;
	getConversation(conversationId: string): Promise<ConversationRecord | undefined>;
	createConversation(input: CreateConversationInput): Promise<ConversationRecord>;
	/** Appends in the given order and returns them as stored, with `seq` set. */
	appendMessage(conversationId: string, input: AppendMessageInput): Promise<ConversationMessage>;
	appendMessages(
		conversationId: string,
		inputs: readonly AppendMessageInput[],
	): Promise<readonly ConversationMessage[]>;
	/**
	 * Replaces the conversation's system prompt.
	 *
	 * Implemented as a message at the head of the transcript rather than a
	 * separate field, because the transcript is what gets sent: keeping the
	 * prompt anywhere else would mean two places that can disagree about what
	 * the model was told.
	 *
	 * Any existing `system` message is replaced — there is exactly one — and
	 * passing an empty string removes it, since "no system prompt" is a real
	 * state and not the same as a blank instruction.
	 */
	setSystemPrompt(conversationId: string, content: string): Promise<ConversationRecord>;
	/** Renames a conversation. Throws when the id is unknown. */
	renameConversation(conversationId: string, title: string): Promise<ConversationRecord>;
	deleteConversation(conversationId: string): Promise<boolean>;
}

/**
 * Field names whose *values* must never be persisted.
 *
 * `apiKeyRef` and friends are deliberately not matched: a `…Ref` field is a
 * pointer into the `SecretStore`, and persisting the pointer is exactly the
 * design (see `PersistedProviderConfig`). Only the value behind it is off
 * limits.
 */
const SECRET_FIELD_PATTERN =
	/(api[_-]?key|secret|token|password|passwd|authorization|bearer|credential|private[_-]?key)/i;

/** A field that names a reference rather than holding the secret itself. */
const REFERENCE_FIELD_PATTERN = /ref$/i;

/**
 * Throws when a value carries a secret-looking field.
 *
 * The structural rule — "only declared fields are persisted" — is enforced by
 * the `DataStore` port, whose record types have no place for a secret; this is
 * the runtime guard for callers that build a record dynamically. It matches on
 * the *key* only, never the value, so no secret has to be inspected in order to
 * be rejected.
 */
export function assertNoSecretFields(value: unknown, where = 'record'): void {
	for (const key of Object.keys(asRecord(value, where))) {
		if (REFERENCE_FIELD_PATTERN.test(key)) {
			continue;
		}
		if (SECRET_FIELD_PATTERN.test(key)) {
			throw new ValidationError(
				`Refusing to persist "${key}" in ${where}: secrets belong in the SecretStore, by reference only`,
				{ details: { field: key, where } },
			);
		}
	}
}

/**
 * Converts a runtime history into append inputs.
 *
 * Every role is kept, `system` included. It used to be dropped on the grounds
 * that a system prompt is assembled per request from configuration — but that
 * reasoning assumed the prompt lived outside the transcript, and now it is part
 * of the conversation the user edits. Dropping it here would silently discard
 * the very message the user just typed.
 */
export function toAppendInputs(
	messages: readonly ChatMessage[],
): readonly AppendMessageInput[] {
	return messages.map((message) => ({
		role: message.role as ConversationRole,
		content: message.content,
		...(message.toolCallId !== undefined ? { toolCallId: message.toolCallId } : {}),
		...(message.toolCalls !== undefined ? { toolCalls: message.toolCalls } : {}),
	}));
}

function asRecord(value: unknown, where: string): Record<string, unknown> {
	if (typeof value !== 'object' || value === null || Array.isArray(value)) {
		throw new ValidationError(`${where} must be an object`, { details: { received: typeof value } });
	}
	return value as Record<string, unknown>;
}